package com.longing.longing.mock;

import com.longing.longing.api.user.Provider;
import com.longing.longing.api.user.domain.User;
import com.longing.longing.api.user.service.port.UserRepository;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;

import java.util.ArrayList;
import java.util.List;
import java.util.Objects;
import java.util.Optional;

public class FakeUserRepository implements UserRepository {

    private final Long autoGeneratedId = 1L;
    private final List<User> data = new ArrayList<>();
    /** {userId, blockedUserId} */
    private final List<long[]> blocks = new ArrayList<>();
    private int blockIfAbsentCalls = 0;

    @Override
    public User save(User user) {
        if (user.getId() == null || user.getId() == 0) {
            User newUser = User.builder()
                    .id(autoGeneratedId)
                    .email(user.getEmail())
                    .name(user.getName())
                    .picture(user.getPicture())
                    .role(user.getRole())
                    .providerId(user.getProviderId())
                    .introduction(user.getIntroduction())
                    .nationality(user.getNationality())
                    .provider(user.getProvider())
                    .build();
            data.add(newUser);
            return newUser;
        } else {
            data.removeIf(item -> Objects.equals(item.getId(), user.getId()));
            data.add(user);
            return user;
        }
    }

    @Override
    public Optional<User> findById(long id) {
        return data.stream().filter(item -> item.getId().equals(id)).findAny();
    }

    @Override
    public Optional<User> findByEmail(String email) {
        return Optional.empty();
    }

    @Override
    public Optional<User> findByProviderId(String providerId) {
        return Optional.empty();
    }

    @Override
    public Optional<User> findByEmailAndProvider(String email, Provider provider) {
        return data.stream().filter(
                item -> item.getEmail().equals(email) && item.getProvider().equals(provider)
        ).findAny();
    }

    @Override
    public void deleteById(long id) {

    }

    @Override
    public boolean isBlocked(long userId, long blockedUserId) {
        return blocks.stream().anyMatch(block -> block[0] == userId && block[1] == blockedUserId);
    }

    @Override
    public boolean blockIfAbsent(User user, User blockedUser) {
        blockIfAbsentCalls++;
        if (isBlocked(user.getId(), blockedUser.getId())) {
            return false;
        }
        blocks.add(new long[]{user.getId(), blockedUser.getId()});
        return true;
    }

    @Override
    public int unblock(long userId, long blockedUserId) {
        int before = blocks.size();
        blocks.removeIf(block -> block[0] == userId && block[1] == blockedUserId);
        return before - blocks.size();
    }

    public int getBlockIfAbsentCalls() {
        return blockIfAbsentCalls;
    }

    @Override
    public Page<User> findBlockedUserList(Long id, String keyword, Pageable pageable) {
        return null;
    }
}
